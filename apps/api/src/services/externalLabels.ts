export const EXTERNAL_FORMATS = ['csv', 'json', 'jsonl'] as const;
export type ExternalFormat = (typeof EXTERNAL_FORMATS)[number];
export const MAX_IMPORT_BYTES = 10 * 1024 * 1024;
const ID = 'authenq_task_id';

function csvCell(v: unknown): string {
  const raw = v === null || v === undefined ? '' : typeof v === 'object' ? JSON.stringify(v) : String(v);
  const s = /^[=+\-@\t\r]/.test(raw) ? `'${raw}` : raw;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/**
 * Exports a project's synthetic records for labeling in an outside tool. Only synthetic rows leave
 * AuthenQ, locked test records are never included, and the transfer is recorded as a Canary send.
 */
export async function externalExport(ctx: RequestContext, projectId: string, input: { format: ExternalFormat; onlyUnlabeled: boolean; recipient: string }) {
  const p = await getProjectOrThrow(ctx, projectId);
  const set = await prisma.syntheticSet.findFirst({ where: { id: p.setId, orgId: ctx.orgId, deletedAt: null }, select: { approvalStatus: true } });
  if (set?.approvalStatus !== 'APPROVED') throw badRequest('The synthetic set behind this project is not approved, so its records cannot be sent outside AuthenQ. An administrator must approve it first.');
  const tasks = await prisma.task.findMany({
    where: { projectId, OR: [{ gold: { is: null } }, { gold: { split: { not: 'LOCKED_TEST' } } }], ...(input.onlyUnlabeled ? { status: { in: ['OPEN', 'SKIPPED', 'FLAGGED'] } } : {}) },
    orderBy: { ordinal: 'asc' },
    include: { syntheticRow: { select: { id: true, data: true } } },
  });
  if (!tasks.length) throw badRequest('There are no records to export with these options.');
  const fields = [...new Set([...p.textFields, ...p.contextFields])];
  const records: Record<string, unknown>[] = tasks.map((t) => {
    const d = t.syntheticRow.data as Record<string, unknown>;
    return { [ID]: t.id, record_number: t.ordinal, ...Object.fromEntries(fields.map((f) => [f, d[f] ?? null])), label: '', note: '' };
  });
  const cols = [ID, 'record_number', ...fields, 'label', 'note'];
  const data =
    input.format === 'csv'
      ? `${cols.join(',')}\n${records.map((r) => cols.map((c) => csvCell(r[c])).join(',')).join('\n')}\n`
      : input.format === 'json'
        ? JSON.stringify(records, null, 2)
        : `${records.map((r) => JSON.stringify(r)).join('\n')}\n`;
  const labels = labelsOf(p);
  const send = await prisma.$transaction(async (tx) => {
    const send = await tx.send.create({
      data: { orgId: ctx.orgId, setId: p.setId, recipient: input.recipient, recipientType: 'EXTERNAL_TOOL', channel: `External labeling file (${input.format.toUpperCase()})`, projectId, recordCount: tasks.length, sentById: ctx.userId },
    });
    const registry = await tx.canaryRegistry.findMany({ where: { syntheticRowId: { in: tasks.map((t) => t.syntheticRow.id) } }, select: { id: true } });
    for (let i = 0; i < registry.length; i += 5000) {
      await tx.exposure.createMany({ data: registry.slice(i, i + 5000).map((r) => ({ orgId: ctx.orgId, sendId: send.id, registryId: r.id })), skipDuplicates: true });
    }
    await audit(ctx, { action: 'labeling.external_export', resourceType: 'label_project', resourceId: projectId, summary: `Exported ${tasks.length} synthetic records to "${input.recipient}" for external labeling (${input.format.toUpperCase()})`, details: { sendId: send.id, exposures: registry.length } }, tx);
    return send;
  });
  const checksum = createHash('sha256').update(data).digest('hex');
  const manifest = { project: { id: p.id, name: p.name }, syntheticSetId: p.setId, table: p.tableName, sendId: send.id, recipient: input.recipient, format: input.format, records: tasks.length, columns: cols, labels: labels.map((l) => l.value), excluded: 'Locked test records are never exported.', sha256: checksum, createdAt: new Date().toISOString() };
  const readme = [
    `# ${p.name}: external labeling template`,
    '',
    'All records are synthetic. They were generated by AuthenQ Twin and contain no real source data.',
    '',
    `Fill in the \`label\` column with exactly one of: ${labels.map((l) => `\`${l.value}\``).join(', ')}. Leave it empty to skip a record. \`note\` is optional.`,
    `Do not change \`${ID}\`; AuthenQ uses it to match labels to records when you import the file again.`,
    '',
    '## Labels',
    ...labels.map((l) => `- **${l.value}**: ${l.description || 'no description'}`),
  ].join('\n');
  const zip = createZip([
    { name: `data.${input.format}`, data },
    { name: 'manifest.json', data: JSON.stringify(manifest, null, 2) },
    { name: 'README.md', data: readme },
  ]);
  return { filename: `${p.name.replace(/[^\w-]+/g, '_').slice(0, 60)}-external-labeling.zip`, zip, sendId: send.id, records: tasks.length };
}

type Row = Record<string, unknown>;

function parseImport(content: string, filename: string): Row[] {
  const ext = filename.toLowerCase().split('.').pop();
  try {
    if (ext === 'csv' || ext === 'tsv') return parseCsv(content, { columns: (h: string[]) => h.map((x) => x.trim().toLowerCase()), skip_empty_lines: true, bom: true, delimiter: ext === 'tsv' ? '\t' : ',', relax_column_count: true }) as Row[];
    if (ext === 'json') {
      const v = JSON.parse(content) as unknown;
      if (!Array.isArray(v)) throw new Error('The JSON file must contain an array of records.');
      return v as Row[];
    }
    if (ext === 'jsonl') return content.split(/\r?\n/).filter((l) => l.trim()).map((l, i) => {
      try { return JSON.parse(l) as Row; } catch { throw new Error(`Line ${i + 1} is not valid JSON.`); }
    });
  } catch (e) {
    throw badRequest(`The file could not be read: ${(e as Error).message}`);
  }
  throw badRequest('Upload a CSV, TSV, JSON or JSONL file.');
}

export interface ImportIssue { row: number; taskId: string | null; problem: string }

/**
 * Validates labels from an outside tool and, unless this is a dry run, imports the valid ones.
 * Labels on records that already have a different human label are kept, and the record is flagged for a project manager.
 */
export async function importExternalLabels(ctx: RequestContext, projectId: string, input: { content: string; filename: string; dryRun: boolean; acceptErrors?: boolean }) {
  const p = await getProjectOrThrow(ctx, projectId);
  const rows = parseImport(input.content, input.filename);
  if (!rows.length) throw badRequest('The file contains no records.');
  if (rows.length > 50_000) throw badRequest('Import at most 50,000 records at a time.');
  const allowed = new Set(labelsOf(p).map((l) => l.value));
  const lowerToLabel = new Map([...allowed].map((l) => [l.toLowerCase(), l]));
  const ids = rows.map((r) => String(r[ID] ?? '').trim()).filter(Boolean);
  const tasks = new Map(
    (await prisma.task.findMany({ where: { projectId, id: { in: ids.filter((i) => /^[0-9a-f-]{36}$/i.test(i)) } }, include: { gold: { select: { split: true } } } })).map((t) => [t.id, t]),
  );
  const errors: ImportIssue[] = [];
  const conflicts: ImportIssue[] = [];
  const seen = new Set<string>();
  const valid: { taskId: string; label: string; note?: string; conflict: boolean }[] = [];
  let empty = 0;
  rows.forEach((r, i) => {
    const row = i + 1;
    const taskId = String(r[ID] ?? '').trim();
    const raw = String(r.label ?? '').trim();
    if (!taskId) return errors.push({ row, taskId: null, problem: `Missing ${ID}.` });
    const task = tasks.get(taskId);
    if (!task) return errors.push({ row, taskId, problem: 'No record with this ID exists in this project.' });
    if (seen.has(taskId)) return errors.push({ row, taskId, problem: 'This record appears more than once in the file.' });
    seen.add(taskId);
    if (!raw) { empty++; return; }
    const label = allowed.has(raw) ? raw : lowerToLabel.get(raw.toLowerCase());
    if (!label) return errors.push({ row, taskId, problem: `"${raw.slice(0, 60)}" is not a label in this project.` });
    if (task.gold) return errors.push({ row, taskId, problem: task.gold.split === 'LOCKED_TEST' ? 'Locked test records cannot be labeled outside AuthenQ.' : 'Gold records must be labeled in AuthenQ.' });
    const current = (task.finalLabels as { label?: string } | null)?.label;
    const conflict = !!current && current !== label;
    if (conflict) conflicts.push({ row, taskId, problem: `Already labeled "${current}" in AuthenQ; the file says "${label}". Flagged for a project manager.` });
    valid.push({ taskId, label, note: r.note ? String(r.note).slice(0, 1000) : undefined, conflict });
  });
  const summary = { rows: rows.length, valid: valid.length, empty, errors, conflicts, imported: 0, batchId: null as string | null };
  if (input.dryRun) return summary;
  if (errors.length && !input.acceptErrors) throw badRequest(`${errors.length} row(s) have problems. Fix the file, or confirm that only the ${valid.length} valid row(s) should be imported.`);
  if (!valid.length) throw badRequest('There are no valid labels to import.');
  const batchId = randomUUID();
  await prisma.$transaction(
    async (tx) => {
      const rowsWithIds = valid.map((v) => ({ ...v, labelId: randomUUID() }));
      for (let i = 0; i < rowsWithIds.length; i += 5000) {
        await tx.label.createMany({
          data: rowsWithIds.slice(i, i + 5000).map((v) => ({ id: v.labelId, orgId: ctx.orgId, projectId, taskId: v.taskId, userId: ctx.userId, values: { label: v.label } as Prisma.InputJsonValue, source: 'EXTERNAL_IMPORT', kind: 'WORK', guidelineVersionId: p.activeGuidelineVersionId, note: `import:${batchId}${v.note ? ` ${v.note}` : ''}`.slice(0, 1000) })),
        });
      }
      const flagged = rowsWithIds.filter((v) => v.conflict).map((v) => v.taskId);
      for (let i = 0; i < flagged.length; i += 5000) await tx.task.updateMany({ where: { projectId, id: { in: flagged.slice(i, i + 5000) } }, data: { status: 'FLAGGED' } });
      const accepted = rowsWithIds.filter((v) => !v.conflict);
      for (let i = 0; i < accepted.length; i += 5000) {
        const c = accepted.slice(i, i + 5000);
        await tx.$executeRaw`UPDATE tasks AS t SET status = 'LABELED', "finalLabels" = jsonb_build_object('label', v.label), "finalSource" = 'EXTERNAL_IMPORT', "finalLabelId" = v.lid, "updatedAt" = now()
          FROM unnest(${c.map((x) => x.taskId)}::uuid[], ${c.map((x) => x.labelId)}::uuid[], ${c.map((x) => x.label)}::text[]) AS v(tid, lid, label)
          WHERE t.id = v.tid AND t."projectId" = ${projectId}::uuid`;
      }
      await audit(ctx, { action: 'labeling.external_import', resourceType: 'label_project', resourceId: projectId, summary: `Imported ${valid.length} external label(s) from "${input.filename.slice(0, 120)}" (${conflicts.length} conflict(s), ${errors.length} rejected row(s))`, details: { batchId, errors: errors.length, conflicts: conflicts.length } }, tx);
    },
    { timeout: 120_000 },
  );
  return { ...summary, imported: valid.length, batchId };
}
